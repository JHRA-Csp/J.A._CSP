# JA, Silly Sentences activity

Verb = input("Tell me a verb ending in ing: ").strip().capitalize()
Place = input("Tell me a place: ").strip().capitalize()
Colour = input("Tell me a colour: ").strip().capitalize()
Travel = input("Tell me a way to travel: ").strip().capitalize()
Emotion = input("Tell me an emotion: ").strip().capitalize()
Animal = input("Tell me an animal: ").strip().capitalize()

print("I was running late for "+Verb+" job in "+Place+" when my "+Colour+" "+Travel+" was attacked by a "+Emotion+" "+Animal+"!")